def tr(language_code: str | None, key: str, **kwargs: Any) -> str:
    normalized = normalize_language_code(language_code)
    template = TRANSLATIONS.get(normalized, {}).get(key)
    if template is None and normalized not in {DEFAULT_LANGUAGE, "en"}:
        template = TRANSLATIONS["en"].get(key)
    if template is None:
        template = TRANSLATIONS[DEFAULT_LANGUAGE].get(key) or key
    return template.format(**kwargs) if kwargs else template


def resolve_localized_text(value: Any, language_code: str | None = None, fallback: str = "") -> str:
    normalized = normalize_language_code(language_code)
    if isinstance(value, dict):
        candidate = value.get(normalized) or value.get("en") or value.get(DEFAULT_LANGUAGE)
        if candidate:
            return str(candidate)
        for item in value.values():
            if item:
                return str(item)
        return fallback
    if value is None:
        return fallback
    text = str(value).strip()
    return text or fallback


def localize_market_text(value: Any, language_code: str | None = None, fallback: str = "") -> str:
    normalized = normalize_language_code(language_code)
    text = resolve_localized_text(value, normalized, fallback=fallback)
    if normalized == DEFAULT_LANGUAGE or not text:
        return text
    result = text
    for pattern, replacement in MARKET_TERM_PATTERNS.get(normalized, ()):
        result = re.sub(pattern, replacement, result, flags=re.IGNORECASE)
    return re.sub(r"\s{2,}", " ", result).strip()


def get_localized_market_category_label(category: Any, language_code: str | None = None) -> str:
    normalized = normalize_language_code(language_code)
    raw_name = resolve_localized_text(category.get("name") if isinstance(category, dict) else category, normalized)
    lowered = raw_name.lower()
    for keyword, labels in MARKET_CATEGORY_KEYWORD_LABELS:
        if keyword in lowered:
            return labels.get(normalized) or labels.get("en") or labels.get(DEFAULT_LANGUAGE) or raw_name
    return localize_market_text(raw_name, normalized, fallback=raw_name)
